#!/usr/bin/env python3
"""
write_native_manifest.py - Write native-binaries.sexp from a nightly manifest.

native-binaries.sexp is what the system loader (fetch-binaries.lisp) reads to
find, download and verify the openDAQ native libraries for the current
platform.  It is derived from the manifest of the pinned
opendaq-bindings-nightly release, so the libraries the loader downloads are
exactly the ones the committed bindings were generated for.

Usage:
    python write_native_manifest.py tmp/nightly/<tag>/manifest.json native-binaries.sexp
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    manifest = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    upstream = manifest["upstream"]

    lines = [
        ";; Generated by tools/write_native_manifest.py from the pinned nightly (opendaq-nightly.lock)",
        ";; -- do not edit by hand; run `make bump-nightly TAG=...` to move to another release.",
        f'(:tag "{manifest["tag"]}"',
        f' :base-url "{manifest["base_url"]}"',
        f' :opendaq-repo "{upstream["repo"]}"',
        f' :opendaq-ref "{upstream["ref"]}"',
        f' :opendaq-sha "{upstream["sha"]}"',
        " :archives",
        " (",
    ]
    for triple, asset in sorted(manifest["natives"].items()):
        lines.append(f'  ("{triple}" "{asset["file"]}" "{asset["sha256"]}")')
    lines.append(" ))")

    Path(sys.argv[2]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
